"""Every ezmath snippet shown on the "ezmath vs LaTeX" page must compile.

The snippets live in site/assets/data/comparison.json (generated by
scripts/build_site_data.py from a single source of truth). This test
recompiles each one with the real compiler so the page can never ship
code that does not work.
"""

import json
import os
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'src'))
from compiler import compile_ezmath
from compiler import pipeline as _pipeline

COMP = ROOT / 'site' / 'assets' / 'data' / 'comparison.json'


@pytest.fixture(autouse=True)
def _stub_typst(monkeypatch):
    _stub = type('_TypstStub', (), {'compile': staticmethod(lambda *a, **k: None)})()
    monkeypatch.setattr(_pipeline, 'typst', _stub)


def _pairs():
    if not COMP.is_file():
        pytest.skip('comparison.json not generated')
    return json.loads(COMP.read_text(encoding='utf-8'))


def test_comparison_file_exists():
    assert COMP.is_file()


def test_every_ezmath_snippet_compiles(tmp_path):
    pairs = _pairs()
    assert len(pairs) >= 8
    for idx, pair in enumerate(pairs):
        code = pair['ezmath']
        src = tmp_path / f'pair_{idx}.ezmath'
        src.write_text(code, encoding='utf-8')
        out = tmp_path / f'pair_{idx}.pdf'
        ok = compile_ezmath(str(src), str(out))
        assert ok is not False, f"snippet {idx} ({pair.get('title')}) failed to compile"


def test_counts_are_computed_not_hand_typed():
    pairs = _pairs()
    for pair in pairs:
        assert pair['latex_chars'] == len(pair['latex'])
        assert pair['ezmath_chars'] == len(pair['ezmath'])
        assert pair['latex_lines'] == pair['latex'].count('\n') + 1
        assert pair['ezmath_lines'] == pair['ezmath'].count('\n') + 1